// Regenerates docs/API.md from the route registry. Run from the repo root: `npx tsx scripts/gen-api-doc.ts`
import { writeFileSync } from "node:fs";
import * as contracts from "../src/contracts/index";
import { endpoints } from "../src/contracts/registry";

/** Export name of a schema object (first export that is this exact object). */
const nameOf = (schema: unknown) =>
  schema ? (Object.entries(contracts).find(([, v]) => v === schema)?.[0] ?? "?") : "";

const rows = endpoints.map((e) => {
  const req = (["params", "query", "body"] as const)
    .filter((k) => e[k])
    .map((k) => `${k}: \`${nameOf(e[k])}\``)
    .join("<br>");
  const auth = e.auth + (e.idempotent ? " · Idempotency-Key" : "");
  return `| ${e.method} | \`${e.path}\` | ${auth} | ${req || "—"} | \`${nameOf(e.response)}\` | ${e.task} |`;
});

const doc = `# ParkShare API

Generated by \`npx tsx scripts/gen-api-doc.ts\` from \`src/contracts/registry.ts\`. Do not edit by hand.

Schemas live in \`src/contracts/*\` and are re-exported from \`@/contracts\`. Every handler
uses \`route()\` from \`src/server/http/route.ts\`, so errors share one envelope:
\`{ "error": { "code", "message", "details"? } }\` (\`ErrorEnvelope\`). Status codes:
400 validation_error, 401 unauthorized, 403 forbidden, 404 not_found, 409 conflict,
422 unprocessable, 429 rate_limited, 500 internal_error, 501 not_implemented (stub).

Conventions: money is \`{ paise, currency: "INR" }\`; times are ISO 8601 UTC strings;
ids are UUIDs; list endpoints take \`cursor\`/\`limit\` and return \`{ items, nextCursor }\`.
Auth \`user\` = signed-in session; \`admin\` = ADMIN role. Mutating admin requests require
\`reason\`. "Idempotency-Key" endpoints must be called with that header.

| Method | Path | Auth | Request | Response | Task |
|---|---|---|---|---|---|
${rows.join("\n")}
`;

writeFileSync("docs/API.md", doc);
console.log(`docs/API.md: ${endpoints.length} endpoints`);
